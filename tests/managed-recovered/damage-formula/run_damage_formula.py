def toolchain_record():
    files = [DOTNET, CSC, CSC_RUNTIMECONFIG, os.path.join(SDK, ".version")]
    files += sorted(os.path.join(CSC.rsplit("\\", 1)[0], name) for name in os.listdir(os.path.dirname(CSC))
                    if name.endswith((".dll", ".json")))
    files += sorted(os.path.join(REFDIR, name) for name in os.listdir(REFDIR) if name.endswith(".dll"))
    files += sorted(os.path.join(RUNTIME_DIR, name) for name in os.listdir(RUNTIME_DIR)
                    if os.path.isfile(os.path.join(RUNTIME_DIR, name)))
    entries = []
    seen = set()
    for path in files:
        path = lex(path)
        if not os.path.isfile(path):
            die("toolchain file missing: " + path)
        if path in seen:
            continue
        seen.add(path)
        data = read_bytes(path)
        entries.append({"path": path, "bytes": len(data), "sha256": sha256_bytes(data)})
    entries.sort(key=lambda e: e["path"])
    return entries


