def execute(manifest_name, expected_sha):
    if not re.fullmatch(r"[0-9a-fA-F]{64}", expected_sha or ""):
        die("--expected-manifest-sha must be 64 hex characters")
    expected_sha = expected_sha.lower()
    if (not manifest_name or os.path.basename(manifest_name) != manifest_name
            or "/" in manifest_name or "\\" in manifest_name or manifest_name in (".", "..")
            or not manifest_name.endswith(".json")):
        die("--manifest must be a bare .json basename inside scratch")

    assert_no_reparse(SCRATCH)
    manifest_path = SCRATCH / manifest_name
    assert_no_reparse(manifest_path)
    if not os.path.isfile(lex(manifest_path)):
        die("manifest not found: " + str(manifest_path))
    if os.path.commonpath([lex(manifest_path), lex(SCRATCH)]) != lex(SCRATCH):
        die("manifest escapes scratch")
    if sha256_file(manifest_path) != expected_sha:
        die("externally supplied manifest hash does not match")
    manifest = json.loads(read_bytes(manifest_path).decode("utf-8"))
    if manifest.get("schema") != MANIFEST_SCHEMA:
        die("manifest schema is not executable: %r" % manifest.get("schema"))
    assert_tree_no_reparse(SCRATCH)

    verify_sources_and_bodies(manifest)
    verify_authored(manifest)
    verify_preservation(manifest)
    if manifest["toolchain"]["file"] != "provenance/toolchain.json":
        die("toolchain pin does not reference the prepared provenance file")
    entries, toolchain_sha = load_toolchain()
    if manifest["toolchain"]["sha256"] != toolchain_sha:
        die("toolchain pin mismatch")
    verify_toolchain(entries)
    if manifest.get("matchup_raw_citation") != verify_matchup_row():
        die("matchup raw-row citation does not match the current raw row")
    plan = verify_plan(manifest["execute_plan"], ref_closure(entries))

    for rel in ("build", "run"):
        assert_absent(SCRATCH / rel)
    for rel in EXECUTE_WRITES:
        assert_absent(SCRATCH / rel)
    mkdir_new(SCRATCH / "build")
    mkdir_new(SCRATCH / "run")

    receipts = SCRATCH / "receipts"
    try:
        compiler = subprocess.run(
            plan["compiler_argv"], cwd=plan["compiler_cwd"], env=plan["csc_env"],
            capture_output=True, timeout=plan["timeouts_seconds"]["csc"],
        )
    except subprocess.TimeoutExpired:
        die("direct csc compilation timed out; nothing was deleted")
    write_new(receipts / "csc.stdout.txt", compiler.stdout)
    write_new(receipts / "csc.stderr.txt", compiler.stderr)
    if compiler.returncode != 0 or not os.path.isfile(lex(SCRATCH / DLL)):
        print("CSC_EXIT=" + str(compiler.returncode))
        print(compiler.stdout.decode(errors="replace"))
        print(compiler.stderr.decode(errors="replace"))
        die("direct csc compilation failed")

    try:
        harness = subprocess.run(
            plan["runtime_argv"], cwd=plan["runtime_cwd"], env=plan["run_env"],
            capture_output=True, timeout=plan["timeouts_seconds"]["harness"],
        )
    except subprocess.TimeoutExpired:
        die("harness execution timed out; nothing was deleted")
    write_new(receipts / "harness.stdout.txt", harness.stdout)
    write_new(receipts / "harness.stderr.txt", harness.stderr)

    post = {"byte_equality": True, "authored": True, "preservation": True}
    try:
        verify_sources_and_bodies(manifest)
        verify_authored(manifest)
        verify_preservation(manifest)
    except SystemExit:
        post = {"byte_equality": False, "authored": False, "preservation": False}
        pass

    stdout = harness.stdout.decode(errors="replace")
    passed = (harness.returncode == 0 and "RESULT=PASS" in stdout
              and "ASSERTIONS_FAILED=0" in stdout)
    receipt = {
        "task": "RE-GAMEPLAY-DAMAGE-FORMULA01",
        "mode": "execute",
        "manifest_file": manifest_name,
        "manifest_sha256": expected_sha,
        "compiler_exit": compiler.returncode,
        "harness_exit": harness.returncode,
        "harness_result": "PASS" if passed else "FAIL",
        "post_checks": post,
        "dll_sha256": sha256_file(SCRATCH / DLL) if os.path.isfile(lex(SCRATCH / DLL)) else None,
        "csc_stdout_sha256": sha256_bytes(compiler.stdout),
        "harness_stdout_sha256": sha256_bytes(harness.stdout),
    }
    write_new(receipts / "execute-receipt.json",
              json.dumps(receipt, indent=2, sort_keys=True).encode() + b"\n")

    print(stdout)
    if harness.stderr:
        print(harness.stderr.decode(errors="replace"), file=sys.stderr)
    print("CSC_EXIT=" + str(compiler.returncode))
    print("HARNESS_EXIT=" + str(harness.returncode))
