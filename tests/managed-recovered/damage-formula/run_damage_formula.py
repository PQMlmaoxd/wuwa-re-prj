def check_source_contract(bodies):
    by_name = {body["name"]: body["slice"] for body in bodies}
    hurt = by_name["CalculateHurt"]
    for token in (b"RandomSeed", b"RandomSystem", b"Math.Ceiling", b"Math.Floor", b"(int)", b"(long)"):
        if token in hurt:
            die("CalculateHurt source contract violated: found " + token.decode())
    matchup = by_name["CalculateElementMatchUpRate"]
    if matchup.count(b"1.0") < 8:
        die("CalculateElementMatchUpRate no longer shows all-1.0 arms")
    getter = by_name["AttributeSnapshot.GetCurrentValue"]
    if b"CurrentValues[(int)attrId]" not in getter:
        die("GetCurrentValue no longer reads CurrentValues by index")
    for body in bodies:
        if b"\t}\n" not in body["slice"][-8:]:
            die("body does not end with a tab-indented closing brace: " + body["name"])
    harness = read_bytes(HARNESS / "HarnessTests.cs").decode("utf-8")
    for label, _value, bits in spot_oracles():
        literal = "0x%016XUL" % bits
        if literal not in harness:
            die("harness oracle literal missing for " + label + ": " + literal)


def spot_oracles():
    k = float("9.9999997473787516E-05")
    num = 10000.0 * k
    values = {
        "D01a": num * 128.0,
        "D01b": (num * 128.0) * 0.5,
        "D04c": 64.0 * (1.0 / (1.0 + 1.0 * 5.0)),
        "D05c": 64.0 * (1.0 + 10000.0 * k),
        "D06a": num * 5000.0,
    }
    out = []
    for label, value in values.items():
        bits = struct.unpack("<Q", struct.pack("<d", value))[0]
        out.append((label, value, bits))
    return out


