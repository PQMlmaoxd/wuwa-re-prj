def verify_toolchain(entries):
    stored = {}
    for entry in entries:
        path = lex(entry["path"])
        if not os.path.isabs(path):
            die("toolchain path is not absolute: " + path)
        if path in stored:
            continue
        if not os.path.isfile(path):
            die("toolchain file missing: " + path)
        if is_reparse(path):
            die("toolchain file is a reparse point: " + path)
        data = read_bytes(path)
        if len(data) != entry["bytes"] or sha256_bytes(data) != entry["sha256"]:
            die("toolchain hash/size drift: " + path)
        stored[path] = (entry["bytes"], entry["sha256"])
    fresh = {e["path"]: (e["bytes"], e["sha256"]) for e in toolchain_record()}
    if stored != fresh:
        die("toolchain entry set differs from a fresh local record")
    return fresh


def ref_closure(entries):
    refdir = os.path.normcase(lex(REFDIR))
    refs = sorted(
        {
            lex(e["path"])
            for e in entries
            if e["path"].lower().endswith(".dll")
            and os.path.normcase(os.path.dirname(lex(e["path"]))) == refdir
        }
    )
    if len(refs) != 163:
        die("unexpected reference pack DLL count: %d" % len(refs))
    return refs


